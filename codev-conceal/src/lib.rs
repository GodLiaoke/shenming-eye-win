fn decode_key() -> u8 {
    // Prevent LLVM from const-folding XOR back into plaintext protocol tokens.
    unsafe { core::ptr::read_volatile(&KEY) }
}

fn decode(hidden: &[u8]) -> String {
    let key = decode_key();
    let bytes: Vec<u8> = hidden.iter().map(|byte| byte ^ key).collect();
    String::from_utf8(bytes).unwrap_or_default()
}

fn intern(hidden: &'static [u8]) -> &'static str {
    static CACHE: OnceLock<Mutex<HashMap<Vec<u8>, &'static str>>> = OnceLock::new();
    let cache = CACHE.get_or_init(|| Mutex::new(HashMap::new()));
    let mut guard = cache
        .lock()
        .unwrap_or_else(|poisoned| poisoned.into_inner());
    if let Some(value) = guard.get(hidden) {
        return value;
    }
    let leaked: &'static str = Box::leak(decode(hidden).into_boxed_str());
    guard.insert(hidden.to_vec(), leaked);
    leaked
}

pub fn record_magic() -> [u8; 4] {
    let key = decode_key();
    let mut magic = [0_u8; 4];
    for (index, slot) in magic.iter_mut().enumerate() {
        *slot = unsafe { core::ptr::read_volatile(&CVM1[index]) } ^ key;
    }
    std::hint::black_box(magic)
}

